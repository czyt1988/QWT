/******************************************************************************
 * Cross-validation harness for QwtBoxStatisticsCalculator.
 *
 * Reads cases from stdin, one case per block:
 *     <id:string> <method:int> <coeff:double> <n:int>
 *     followed by n lines with one double each ("nan"/"inf" allowed)
 *
 * method matches QwtBoxStatisticsCalculator::WhiskerMethod:
 *     0 = Tukey, 1 = Percentile, 2 = MinMax, 3 = StandardDeviation,
 *     4 = StandardError
 *
 * For every case one line is printed:
 *     CASE <id> <whiskerLower> <q1> <median> <q3> <whiskerUpper> <outlierCount> <outlier values...>
 *
 * The case file is generated by boxstats_experiment.py (boxstats_cases.txt);
 * the same script re-computes every case in Python and compares.
 * No timing is performed here by design.
 *****************************************************************************/

#include "qwt_box_statistics.h"
#include "qwt_samples.h"

#include <QVector>

#include <cstdlib>
#include <iomanip>
#include <iostream>
#include <string>

int main()
{
    std::cout << std::setprecision(17);

    std::string id;
    while (std::cin >> id) {
        int method = 0;
        int n      = 0;
        double coeff = 1.5;
        if (!(std::cin >> method >> coeff >> n))
            break;

        QVector< double > raw;
        raw.reserve(n);
        for (int i = 0; i < n; ++i) {
            // read as token and parse with strtod: MSVC's operator>> does
            // not accept the "nan" / "inf" literals
            std::string tok;
            std::cin >> tok;
            raw.append(std::strtod(tok.c_str(), nullptr));
        }

        QwtBoxSample sample;
        QwtBoxOutlierSample outliers;
        QwtBoxStatisticsCalculator::calculateFull(0.0, raw, sample, outliers,
                                                  static_cast< QwtBoxStatisticsCalculator::WhiskerMethod >(method),
                                                  coeff);

        std::cout << "CASE " << id << ' '
                  << sample.whiskerLower << ' '
                  << sample.q1 << ' '
                  << sample.median << ' '
                  << sample.q3 << ' '
                  << sample.whiskerUpper << ' '
                  << sample.outlierCount;
        for (int i = 0; i < outliers.values.size(); ++i)
            std::cout << ' ' << outliers.values[ i ];
        std::cout << '\n';
    }

    return 0;
}
